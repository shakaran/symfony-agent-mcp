/**
 * symfony-agent-mcp
 * Model Context Protocol server for Symfony applications
 *
 * Provides read-only introspection of:
 * - Routes (YAML + PHP 8 attributes)
 * - DI Services
 * - Configuration (framework, security, env vars)
 * - Doctrine entities and database schema
 * - Controllers and their actions
 * - Logs, Database migrations, Composer packages
 * - Symfony Messenger queues and message classes
 * - Form types and field analysis
 * - Symfony Profiler data
 * - Cache pools (Symfony + MCP internal)
 * - Event listeners and subscribers
 * - Console commands
 * - Twig templates and inheritance tree
 * - Translation files and missing-key detection
 * - Symfony Workflow / State Machine inspector
 * - Test suite inventory and source coverage map
 * - Environment variable diff across .env* files
 * - Dead code detector (orphan controllers, unused forms, commands)
 * - API Platform resources, operations, filters, and serialization groups
 * - Symfony Serializer #[Groups], #[SerializedName], #[Ignore] inspection
 * - Security voters, role hierarchy tree, access_control matrix, firewalls
 * - Doctrine repository query analysis and N+1 pattern detection
 * - Symfony Mailer: MAILER_DSN transport, Email classes, Twig email templates
 * - Bundle registry from config/bundles.php with environment and category breakdown
 * - Doctrine lifecycle callbacks (#[PrePersist], #[PostLoad], #[EntityListeners])
 * - HTTP Client scoped clients, options, and service usage scanner
 */

